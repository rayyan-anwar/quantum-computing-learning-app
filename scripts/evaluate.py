def random_circuit(n, depth, rng, dense=True):
    state, ops = q.zero_state(n), []
    for _ in range(depth):
        kind = int(rng.integers(0, 6))
        a = int(rng.integers(0, n))
        if kind < 2 or n == 1:
            m = [q.H, q.T, q.S, q.X, q.Y, q.rx(float(rng.uniform(0, 6))), q.ry(float(rng.uniform(0, 6))), q.rz(float(rng.uniform(0, 6)))][int(rng.integers(0, 8))]
            state = q.apply_1q(state, m, a)
            ops.append(D.op_1q(n, m, a) if dense else None)
        else:
            b = int((a + 1 + rng.integers(0, n - 1)) % n)
            fn, ref = [(q.apply_cnot, D.op_cnot), (q.apply_cz, D.op_cz), (q.apply_swap, D.op_swap), (q.apply_cnot, D.op_cnot)][kind - 2]
            state = fn(state, a, b)
            ops.append(ref(n, a, b) if dense else None)
    return state, ops


def dense_agreement():
    rng = np.random.default_rng(0)
    worst, count = 0.0, 0
    for _ in range(300):
        n = int(rng.integers(1, 7))
        state, ops = random_circuit(n, 30, rng)
        worst = max(worst, float(np.abs(state.reshape(-1) - D.run(n, ops)).max()))
        count += 1
    return {"circuits": count, "qubits": "1-6", "depth": 30, "max_abs_amplitude_difference": worst}


def unitarity_and_norm():
    gates = list(q.FIXED.values()) + [f(t) for f in (q.rx, q.ry, q.rz) for t in np.linspace(0, 2 * np.pi, 13)]
    u = max(float(np.abs(m.conj().T @ m - np.eye(2)).max()) for m in gates)
    rng = np.random.default_rng(1)
    drift = max(abs(float(np.linalg.norm(random_circuit(5, 200, rng, dense=False)[0])) - 1) for _ in range(50))
    return {"gates_checked": len(gates), "max_unitarity_error": u, "circuits_depth_200": 50, "max_norm_drift": drift}


def analytic_examples():
    expected = {"superposition": {"0": .5, "1": .5}, "interference": {"1": 1.0}, "bell": {"00": .5, "11": .5},
                "ghz3": {"000": .5, "111": .5}, "grover2": {"11": 1.0}}
    out = {}
    for k, exp in expected.items():
        p = BY_ID[k]
        r = run_circuit(p["n_qubits"], p["gates"], 10, 0)
        got = dict(zip(r["labels"], r["steps"][-1]["probabilities"]))
        out[k] = max(abs(got.get(s, 0.0) - exp.get(s, 0.0)) for s in set(got) | set(exp))
    rng = np.random.default_rng(2)
    err = 0.0
    for _ in range(200):
        th, ph = float(rng.uniform(0, np.pi)), float(rng.uniform(0, 2 * np.pi))
        r = run_circuit(3, [g("ry", 0, theta=th), g("rz", 0, theta=ph), g("h", 1), g("cnot", 1, 2), g("cnot", 0, 1), g("h", 0),
                            g("cnot", 1, 2), g("cz", 0, 2)], 10, 0)
        err = max(err, float(np.abs(np.array(r["steps"][2]["bloch"][0]) - np.array(r["steps"][-1]["bloch"][2])).max()))
    out["teleportation_200_random_states_max_bloch_error"] = err
    return {"max_probability_error_by_example": {k: v for k, v in out.items() if not k.startswith("tele")},
            "teleportation_200_random_states_max_bloch_error": err}


def sampling_calibration(trials=1000, shots=10000):
    p = np.array([0.5, 0.0, 0.0, 0.5])
    rejects = 0
    for seed in range(trials):
        c = q.sample_counts(p, shots, seed)
        chi2 = sum((c.get(k, 0) - shots / 2) ** 2 / (shots / 2) for k in ("00", "11"))
        rejects += chi2 > 3.841  # chi-square critical value, 1 degree of freedom, alpha = 0.05
    return {"trials": trials, "shots": shots, "false_rejection_rate_at_alpha_0.05": rejects / trials, "expected": 0.05}


def scaling():
    out = {}
    rng = np.random.default_rng(3)
    for n in (2, 4, 6, 8, 10, 12, 14, 16):
        t0 = time.perf_counter()
        random_circuit(n, 50, rng, dense=False)
        out[str(n)] = {"seconds_50_gates": round(time.perf_counter() - t0, 4), "state_MB": round(2 ** n * 16 / 2 ** 20, 3)}
    return out


def to_md(r):
    d, u, a, s, sc, e = r["dense"], r["unitarity"], r["analytic"], r["sampling"], r["scaling"], r["environment"]
    L = ["# Results (generated by `scripts/evaluate.py`)", "",
         f"- Created (UTC): {r['created_utc']}; {e['platform']}; Python {e['python']}; NumPy {e['numpy']}; CPUs {e['cpu_count']}", "",
         "## Simulator verification", "", "| Check | Result |", "|---|---:|",
         f"| Agreement with independent dense-matrix simulation ({d['circuits']} random circuits, {d['qubits']} qubits, depth {d['depth']}) | max amplitude difference {d['max_abs_amplitude_difference']:.1e} |",
         f"| Unitarity of {u['gates_checked']} gates | max error {u['max_unitarity_error']:.1e} |",
         f"| Norm after {u['circuits_depth_200']} circuits of depth 200 on 5 qubits | max drift {u['max_norm_drift']:.1e} |",
         f"| Sampling calibration ({s['trials']} runs of {s['shots']} shots, Bell state, chi-square at 5%) | false-rejection rate {s['false_rejection_rate_at_alpha_0.05']:.3f} (expected 0.05) |", "",
         "## Worked examples against analytic results", "", "| Example | Max probability error |", "|---|---:|"]
    L += [f"| {k} | {v:.1e} |" for k, v in a["max_probability_error_by_example"].items()]
    L += [f"| teleportation of 200 random states (Bloch vector error) | {a['teleportation_200_random_states_max_bloch_error']:.1e} |", "",
          "(Example errors are measured on the 6-decimal values the API returns, so 0.0 means agreement to 6 decimals; the dense comparison above uses full precision.)", "",
          "## Cost of ideal simulation (random circuit of 50 gates)", "", "| Qubits | Seconds | State size (MB) |", "|---:|---:|---:|"]
    L += [f"| {n} | {v['seconds_50_gates']} | {v['state_MB']} |" for n, v in sc.items()]
    L += ["", "Memory and time double with every added qubit; the app caps circuits at 6 qubits. These checks show the simulator is numerically correct for ideal gates, not that it models real hardware noise."]
    return "\n".join(L) + "\n"


def main():
    r = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
         "environment": {"platform": platform.platform(), "python": sys.version.split()[0], "numpy": np.__version__, "cpu_count": __import__("os").cpu_count()},
         "dense": dense_agreement(), "unitarity": unitarity_and_norm(), "analytic": analytic_examples(),
         "sampling": sampling_calibration(), "scaling": scaling()}
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "results.json").write_text(json.dumps(r, indent=2))
    (ROOT / "results" / "RESULTS.md").write_text(to_md(r))
    print(to_md(r))


if __name__ == "__main__":
    main()
